//! High-level actions produced by key handlers (Phase 5 dispatcher façade).

/// Application-level command. Key handlers should eventually emit these
/// instead of mutating `App` inline; a single dispatcher executes them.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Action {
    Quit,
    ToggleHelp,
    OpenProfileManager,
    Lock,
    Sync,
    SearchStart,
    SearchClear,
    MoveUp,
    MoveDown,
    PageUp,
    PageDown,
    Home,
    End,
    FocusNext,
    FocusPrev,
    CopyPassword,
    CopyUsername,
    CopyTotp,
    CopyUri,
    ToggleFavorite,
    ToggleReveal,
    NewLogin,
    EditItem,
    DeleteItem,
    NewFolder,
    OpenGenerator,
    Confirm,
    Cancel,
    SubmitLogin,
    SubmitUnlock,
    ToggleRemember,
    TogglePasswordVisibility,
    SignOutProfile,
}

impl Action {
    pub fn label(&self) -> &'static str {
        match self {
            Self::Quit => "Quit",
            Self::ToggleHelp => "Toggle help",
            Self::OpenProfileManager => "Profile manager",
            Self::Lock => "Lock",
            Self::Sync => "Sync",
            Self::SearchStart => "Search",
            Self::SearchClear => "Clear search",
            Self::MoveUp => "Move up",
            Self::MoveDown => "Move down",
            Self::PageUp => "Page up",
            Self::PageDown => "Page down",
            Self::Home => "First item",
            Self::End => "Last item",
            Self::FocusNext => "Next pane",
            Self::FocusPrev => "Previous pane",
            Self::CopyPassword => "Copy password",
            Self::CopyUsername => "Copy username",
            Self::CopyTotp => "Copy TOTP",
            Self::CopyUri => "Copy URI",
            Self::ToggleFavorite => "Toggle favorite",
            Self::ToggleReveal => "Reveal secrets",
            Self::NewLogin => "New login",
            Self::EditItem => "Edit item",
            Self::DeleteItem => "Delete item",
            Self::NewFolder => "New folder",
            Self::OpenGenerator => "Generator",
            Self::Confirm => "Confirm",
            Self::Cancel => "Cancel",
            Self::SubmitLogin => "Sign in",
            Self::SubmitUnlock => "Unlock",
            Self::ToggleRemember => "Remember",
            Self::TogglePasswordVisibility => "Show/hide password",
            Self::SignOutProfile => "Sign out",
        }
    }
}
